#!/usr/bin/env python3
"""Generate the R6 and R20 analog bench decks and `klt sim` requests (issue #92).

    python3 -I sim/bench/gen_r6_r20.py          # write sim/bench/r6_*.sp, r20_*.sp and *.request.json

R6  TX output return loss (SDD22, 100 ohm differential, DC to 5 GHz, 7.5 GHz stretch):
    bias + predriver + driver_ffe + pad_esd, inlined from design/tx/netlists/. The
    mux outputs are replaced by their DC mid level, so the driver pair is balanced
    and conducting (small-signal operating point, driver on). A 100 ohm
    differential AC port drives the pad; SDD22 = (Zd-100)/(Zd+100) = 2*Vpad/Vs - 1,
    formed with an E source and a series -1 V AC source so ngspice's AC linearisation
    keeps the constant. A second request holds vbn at 0 (tails off) for the
    driver-off reference.
R20 clock quality at the receiving buffer: design/rx/netlists/clk_buf_quad.spice driven by
    an IDEAL 5 GHz quad sine source (not a clock design). Duty and quadrature are
    read off two differential pairs (0/180 and 90/270) so 90/270 is not folded into 0/180.
    Random jitter cannot come from a noise-free transient; slew at the crossing
    (the AM-to-PM conversion factor) is reported and RJ is a declared gap.

Everything here is a bench, not a result: no limits are attached, no spec number is
changed, nothing is recorded. All figures are simulated.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.join(HERE, "..", "..")
TXNET = os.path.join(REPO, "design", "tx", "netlists")
RXNET = os.path.join(REPO, "design", "rx", "netlists")

HBT_LIB = "libs.tech/ngspice/models/cornerHBT.lib"
CAP_LIB = "libs.tech/ngspice/models/cornerCAP.lib"
DIO_LIB = "libs.tech/ngspice/models/cornerDIO.lib"

# Same ganged HBT/CAP/DIO grid as sim/rx/pad_ac.request.json (see sim/rx/tools/gen_requests.py).
PROCESS = [
    {"name": "hbt_typ", "sections": [{"lib": HBT_LIB, "section": "hbt_typ"},
                                     {"lib": CAP_LIB, "section": "cap_typ"},
                                     {"lib": DIO_LIB, "section": "dio_tt"}]},
    {"name": "hbt_bcs", "sections": [{"lib": HBT_LIB, "section": "hbt_bcs"},
                                     {"lib": CAP_LIB, "section": "cap_bcs"},
                                     {"lib": DIO_LIB, "section": "dio_ff"}]},
    {"name": "hbt_wcs", "sections": [{"lib": HBT_LIB, "section": "hbt_wcs"},
                                     {"lib": CAP_LIB, "section": "cap_wcs"},
                                     {"lib": DIO_LIB, "section": "dio_ss"}]},
]
CORNERS = {"process": PROCESS, "temperature_c": [-40, 27, 125],
           "supply_v": {"vdd": [1.08, 1.2, 1.32]}}

CPAD = "100f"  # per-leg placeholder for the empty PDK bondpad model (R18 budget, spec "Pads and ESD")


def inline(netdir, cell):
    with open(os.path.join(netdir, cell + ".spice")) as f:
        return "".join(l for l in f if not l.startswith("**"))


def pad_cell():
    """pad_esd.spice with each `bondpad` instance replaced by a placeholder capacitor."""
    text = inline(TXNET, "pad_esd")
    out, n = [], 0
    for line in text.splitlines():
        m = re.match(r"XXPAD(\d)\s+(\S+)\s+bondpad\b", line)
        if m:
            out.append("CPAD%s %s vss %s" % (m.group(1), m.group(2), CPAD))
            n += 1
        else:
            out.append(line)
    assert n == 2, "pad_esd.spice no longer has two bondpad instances"
    return "\n".join(out) + "\n"


def r6_deck(driver_on):
    L = ["* R6 TX return loss bench (issue #92). A BENCH, not a result: no limits, nothing recorded.",
         "* Generated by sim/bench/gen_r6_r20.py; cells inlined from design/tx/netlists/.",
         "* driver %s: %s" % ("ON" if driver_on else "OFF",
                             "bias live, predriver and driver pair balanced at the mux mid level, FFE slices off"
                             if driver_on else "vbn held at 0 V, every tail off (reference only)"),
         "* PAD MODEL IS A PLACEHOLDER: the PDK bondpad model has no capacitance, so each bondpad is",
         "* replaced by %s to ground. Return loss here is NOT graded against a real pad (see #94)." % CPAD,
         "* rsil is a behavioural stand-in (PDK symbol formula, typical rsh), as in sim/tx/tx_sizing_*.sp.",
         ".subckt rsil 1 2 bn",
         ".param w=0.5e-6 l=0.5e-6 b=0 m=1",
         "R1 1 2 r='(9.0e-6/w + 7.0*l/w)/m' tc1=3.1m",
         ".ends rsil",
         inline(TXNET, "bias"), inline(TXNET, "predriver"), inline(TXNET, "driver_ffe"), pad_cell(),
         "Vdd vdd 0 dc 1.2",
         "* mux outputs held at the mid level of the 0.3 V CML swing (balanced pair)",
         "Bmp mp 0 V='v(vdd)-0.15'", "Bmn mn 0 V='v(vdd)-0.15'",
         "Bqp qp 0 V='v(vdd)-0.15'", "Bqn qn 0 V='v(vdd)-0.15'"]
    if driver_on:
        L.append("Xbias vdd 0 vbn bias")
    else:
        L.append("Bvbn vbn 0 V=0")
    L += ["Xprem vdd 0 mp mn vbn pp pn predriver",
          "Xprep vdd 0 qp qn vbn rp rn predriver",
          "Bvbp0 vbp0 0 V=0", "Bvbp1 vbp1 0 V=0", "Bvbp2 vbp2 0 V=0",
          "Xdrv vdd 0 pp pn rp rn vbn vbp0 vbp1 vbp2 cop con driver_ffe",
          "Xpad vdd 0 cop con padp padn pad_esd",
          "* 100 ohm differential AC port: 2 x 50 ohm, AC-coupled so the driver's DC point is untouched",
          "Vsp sp 0 dc 0 ac 0.5", "Vsn sn 0 dc 0 ac -0.5",
          "Rsp sp spc 50", "Rsn sn snc 50",
          "Csp spc padp 1u", "Csn snc padn 1u",
          "* SDD22 = 2*v(pad diff)/Vs - 1  (Vs = 1 V differential)",
          "Ed a 0 vol='2*(v(padp)-v(padn))'",
          "Vm s a dc 0 ac -1",
          ".ic v(vbn)=0.9"]
    return "\n".join(L) + "\n"


R6_FREQS = (("1e6", "1m"), ("1e8", "0p1g"), ("1e9", "1g"), ("2.5e9", "2p5g"),
            ("5e9", "5g"), ("7.5e9", "7p5g"))


def r6_meas():
    m = []
    for f, tag in R6_FREQS:
        n = "r6_sdd22_%s_db" % tag
        m.append({"name": n, "unit": "dB", "spice": ".meas ac %s find vdb(s) at=%s" % (n, f)})
    m.append({"name": "r6_sdd22_max_to_5g_db", "unit": "dB",
              "spice": ".meas ac r6_sdd22_max_to_5g_db max vdb(s) from=1e6 to=5e9"})
    m.append({"name": "r6_sdd22_max_to_7p5g_db", "unit": "dB",
              "spice": ".meas ac r6_sdd22_max_to_7p5g_db max vdb(s) from=1e6 to=7.5e9"})
    return m


def r20_deck():
    L = ["* R20 clock quality bench (issue #92). A BENCH, not a result: no limits, nothing recorded.",
         "* Generated by sim/bench/gen_r6_r20.py. clk_buf_quad is driven by an IDEAL 5 GHz quadrature",
         "* sine source (common mode 0.8333 vdd, +-150 mV per phase, as sim/rx/latch_regen.sp). This",
         "* is not a clock source design; it isolates the buffer's own duty/quadrature error.",
         "* Load: 20 fF per output (placeholder for the latch clock input, as latch_regen.sp).",
         inline(RXNET, "clk_buf_quad"),
         "Vdd vdd 0 1.2"]
    for n, ph in (("ck0", 0), ("ck180", 180), ("ck90", 90), ("ck270", 270)):
        L.append("B%s %s 0 V=0.8333*v(vdd)+0.15*sin(2*3.14159265*5e9*time+%g*3.14159265/180)"
                 % (n, n, ph))
    L += ["Xclk ck0 ck180 ck90 ck270 vdd 0 b0 b180 b90 b270 clk_buf_quad",
          "Cb0 b0 0 20f", "Cb1 b180 0 20f", "Cb2 b90 0 20f", "Cb3 b270 0 20f",
          "* the two differential pairs the measurements read; pair A = 0/180, pair B = 90/270",
          "Bda da 0 V=v(b0)-v(b180)",
          "Bdb db 0 V=v(b90)-v(b270)"]
    return "\n".join(L) + "\n"


def r20_meas():
    # Cycle selection by td: 1 ns is five periods in, after the start-up transient. Quadrature is the
    # rise-to-rise (nominal 50 ps = 90 deg) and rise-to-fall (nominal 150 ps = 270 deg) delay from pair
    # A to pair B, so the 90 and 270 phases are each graded and not folded into 0/180. Duty is the
    # high time of each pair (nominal 100 ps of a 200 ps period). Slew is the 20-80 % style +-50 mV
    # crossing time, the AM-to-PM factor for the RJ gap in benches.json.
    t = "td=1n"
    return [
        {"name": "r20_period_a_s", "unit": "s",
         "spice": ".meas tran r20_period_a_s trig v(da) val=0 rise=3 %s targ v(da) val=0 rise=4 %s" % (t, t)},
        {"name": "r20_high_a_s", "unit": "s",
         "spice": ".meas tran r20_high_a_s trig v(da) val=0 rise=3 %s targ v(da) val=0 fall=3 %s" % (t, t)},
        {"name": "r20_period_b_s", "unit": "s",
         "spice": ".meas tran r20_period_b_s trig v(db) val=0 rise=3 %s targ v(db) val=0 rise=4 %s" % (t, t)},
        {"name": "r20_high_b_s", "unit": "s",
         "spice": ".meas tran r20_high_b_s trig v(db) val=0 rise=3 %s targ v(db) val=0 fall=3 %s" % (t, t)},
        {"name": "r20_quad_90_s", "unit": "s",
         "spice": ".meas tran r20_quad_90_s trig v(da) val=0 rise=3 %s targ v(db) val=0 rise=3 %s" % (t, t)},
        {"name": "r20_quad_270_s", "unit": "s",
         "spice": ".meas tran r20_quad_270_s trig v(da) val=0 rise=3 %s targ v(db) val=0 fall=3 %s" % (t, t)},
        {"name": "r20_slew_rise_a_s", "unit": "s",
         "spice": ".meas tran r20_slew_rise_a_s trig v(da) val=-0.05 rise=3 %s targ v(da) val=0.05 rise=3 %s" % (t, t)},
        {"name": "r20_slew_rise_b_s", "unit": "s",
         "spice": ".meas tran r20_slew_rise_b_s trig v(db) val=-0.05 rise=3 %s targ v(db) val=0.05 rise=3 %s" % (t, t)},
        {"name": "r20_swing_a_v", "unit": "V",
         "spice": ".meas tran r20_swing_a_v pp v(da) from=1n to=3n"},
        {"name": "r20_swing_b_v", "unit": "V",
         "spice": ".meas tran r20_swing_b_v pp v(db) from=1n to=3n"},
    ]


def request(netlist, analysis, measurements, timeout_s):
    return {
        "engine": "ngspice",
        "netlist": netlist,
        "models": {"pdk": "ihp-sg13g2", "lib": HBT_LIB},
        "corners": CORNERS,
        "analysis": analysis,
        "measurements": measurements,
        "options": {"stage_model_inputs": True, "timeout_s": timeout_s, "keep_artifacts": False},
    }


def write(name, body, req):
    with open(os.path.join(HERE, name + ".sp"), "w") as f:
        f.write(body)
    with open(os.path.join(HERE, name + ".request.json"), "w") as f:
        json.dump(req, f, indent=2)
        f.write("\n")


def main():
    ac = {"kind": "ac", "args": "dec 40 1e6 1e10"}
    write("r6_tx_return_loss_on", r6_deck(True), request("r6_tx_return_loss_on.sp", ac, r6_meas(), 300))
    write("r6_tx_return_loss_off", r6_deck(False), request("r6_tx_return_loss_off.sp", ac, r6_meas(), 300))
    write("r20_clk_quality", r20_deck(),
          request("r20_clk_quality.sp", {"kind": "tran", "args": "2p 4n"}, r20_meas(), 300))


if __name__ == "__main__":
    main()
