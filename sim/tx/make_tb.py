#!/usr/bin/env python3
"""Generate the TX HBT sizing testbench deck and its klt sim request.

Outputs (committed, regenerated by this script):
  sim/tx/tx_sizing_<ffeN>_<corner>.sp / .request.json   six requests: FFE off / all
  three post slices on, x process typ/bcs/wcs; each is 3 supplies x 3 temperatures

What is simulated: bias, predriver (x2), driver_ffe -- the HBT-and-resistor cells,
inlined from design/tx/netlists/ so the deck is self-contained. NOT simulated (they
need PSP103 MOS, blocked on #3): mux2to1_cml, ffe_en, lvl_cml2cmos. pad_esd is also
not in the deck: the PDK ESD diode models are not loaded; a lumped 4 ohm + 100 fF
stand-in per leg (the R18 budget, not the cell) loads each output.

Usage: python3 -I sim/tx/make_tb.py     (from the repo root)
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NET = os.path.join(HERE, "..", "..", "design", "tx", "netlists")
UI = 100e-12
TR = 20e-12  # input edge time

# PRBS-7 (x^7 + x^6 + 1) slice after two static runs.
def prbs7(n, state=0x7F):
    out = []
    for _ in range(n):
        bit = ((state >> 6) ^ (state >> 5)) & 1
        state = ((state << 1) | bit) & 0x7F
        out.append(bit)
    return out

BITS = [0, 0] + [1] * 12 + [0] * 12 + [1] * 12 + prbs7(48)
T_HI = 1.35e-9    # end of the first 12-ones run (steady high)
T_LO = 2.55e-9    # end of the 12-zeros run (steady low)
T_END = (len(BITS) + 2) * UI


def pwl(bits, delay=0.0):
    pts, prev = [], bits[0]
    pts.append("0 %d" % prev)
    for i, b in enumerate(bits[1:], start=1):
        if b != prev:
            t = i * UI + delay
            pts.append("%.4g %d" % (t, prev))
            pts.append("%.4g %d" % (t + TR, b))
            prev = b
    pts.append("%.4g %d" % (T_END, prev))
    return "pwl(" + " ".join(pts) + ")"


def inline(cell):
    with open(os.path.join(NET, cell + ".spice")) as f:
        return "".join(l for l in f if not l.startswith("**"))

# ---------------------------------------------------------------- measurements
MEAS = []

def meas(name, expr, unit, kind, limit=None, how="max", info=""):
    MEAS.append((name, expr, unit, kind, limit, how, info))

# collector nodes (R3: <= 1.32 V). name -> node
COLL = {
    "drv_out_p": "cop", "drv_out_n": "con", "drv_tail_main": "xdrv.em",
    "drv_tail_post0": "xdrv.ep0", "drv_tail_post1": "xdrv.ep1", "drv_tail_post2": "xdrv.ep2",
    "pre_main_outp": "pp", "pre_main_outn": "pn", "pre_main_tail": "xprem.e",
    "pre_post_outp": "rp", "pre_post_outn": "rn", "pre_post_tail": "xprep.e",
    "bias_vbn": "vbn",
}
for k, n in COLL.items():
    meas("vc_max_" + k, "v(%s)" % n, "V", "r3_collector", 1.32)

# reverse Vbe = v(emitter) - v(base), per transistor pair (R3: <= 1.0 V)
REV = {
    "drv_main_p": ("xdrv.em", "pp"), "drv_main_n": ("xdrv.em", "pn"),
    "drv_tail_main": ("xdrv.etm", "vbn"),
    "pre_main_p": ("xprem.e", "mp"), "pre_main_n": ("xprem.e", "mn"),
    "pre_main_tail": ("xprem.et", "vbn"),
    "pre_post_p": ("xprep.e", "qp"), "pre_post_n": ("xprep.e", "qn"),
    "pre_post_tail": ("xprep.et", "vbn"),
    "bias_ref": ("xbias.er", "vbn"),
}
for i in range(3):
    REV["drv_post%d_p" % i] = ("xdrv.ep%d" % i, "rp")
    REV["drv_post%d_n" % i] = ("xdrv.ep%d" % i, "rn")
    REV["drv_post%d_tail" % i] = ("xdrv.etp%d" % i, "vbp%d" % i)
for k, (e, b) in REV.items():
    meas("vbe_rev_max_" + k, "v(%s)-v(%s)" % (e, b), "V", "r3_reverse_vbe", 1.0)

# informational: headroom of the tails and of the switching pairs
INFO = {
    "vce_min_drv_tail_main": "v(xdrv.em)-v(xdrv.etm)",
    "vce_min_pre_main_tail": "v(xprem.e)-v(xprem.et)",
    "vcb_min_drv_pair_p": "v(cop)-v(pp)", "vcb_min_drv_pair_n": "v(con)-v(pn)",
}
for k, e in INFO.items():
    meas(k, e, "V", "info", None, "min")
# collector-emitter voltage across the switching devices (open-base BVCEO is 1.4 V)
for k, e in {"vce_max_drv_pair_p": "v(cop)-v(xdrv.em)", "vce_max_drv_pair_n": "v(con)-v(xdrv.em)",
             "vce_max_pre_main_pair_p": "v(pp)-v(xprem.e)", "vce_max_pre_main_pair_n": "v(pn)-v(xprem.e)",
             "vce_max_pre_post_pair_p": "v(rp)-v(xprep.e)", "vce_max_pre_post_pair_n": "v(rn)-v(xprep.e)"}.items():
    meas(k, e, "V", "info", None, "max")

# first-look R4 / R7 (sizing evidence, not a spec result)
MEAS_RAW = []
meas("r4_peak_vppd", "v(vd)", "V", "r4_first_look", None, "pp")
MEAS_RAW += [
    ("r4_steady_hi", ".meas tran r4_steady_hi find v(vd) at=%.4g" % T_HI, "V"),
    ("r4_steady_lo", ".meas tran r4_steady_lo find v(vd) at=%.4g" % T_LO, "V"),
    ("r7_rise_20_80_s", ".meas tran r7_rise_20_80_s trig v(vd) val=-R7A rise=1 td=2.5n "
     "targ v(vd) val=R7A rise=1 td=2.5n", "s"),
    ("r7_fall_80_20_s", ".meas tran r7_fall_80_20_s trig v(vd) val=R7A fall=1 td=1.3n "
     "targ v(vd) val=-R7A fall=1 td=1.3n", "s"),
    ("idd_avg", ".meas tran idd_avg avg par('-i(vdd)') from=1.5n to=%.4g" % T_END, "A"),
]

R7A = {0: "0.06", 1: "0.04"}  # fixed levels below the smallest steady half-swing; see record

def meas_json(ffe):
    out = []
    for name, expr, unit, kind, limit, how, info in MEAS:
        if how == "pp":
            for suffix, fn in (("max", "max"), ("min", "min")):
                out.append(dict(name=name.replace("peak", "peak_" + suffix), unit=unit,
                                spice=".meas tran %s %s %s" % (name.replace("peak", "peak_" + suffix), fn, expr)))
            continue
        d = dict(name=name, unit=unit,
                 spice=".meas tran %s %s %s" % (name, how, "par('%s')" % expr))
        if limit is not None:
            d["limits"] = {"max": limit}
        out.append(d)
    for name, spice, unit in MEAS_RAW:
        out.append(dict(name=name, unit=unit, spice=spice.replace("R7A", R7A[ffe])))
    return out


def deck(ffe, rscale):
    L = []
    L.append("* TX HBT sizing testbench (issue #21). SIZING EVIDENCE, not a spec result.")
    L.append("* Generated by sim/tx/make_tb.py; cells inlined from design/tx/netlists/.")
    L.append("* Not simulated here (MOS, blocked on #3): mux2to1_cml, ffe_en, lvl_cml2cmos.")
    L.append("* Pad/ESD is a lumped stand-in (4 ohm + 100 fF per leg), not the pad_esd cell.")
    L.append("* Circuit body only: klt sim supplies .lib / .control / .end.")
    L.append("* PDK rsil is an OSDI (r3_cmc) model, which the host ngspice cannot load (#3), so")
    L.append("* rsil is a behavioural stand-in using the PDK symbol's own value formula")
    L.append("* (R = 9e-6/w + 7.0*l/w ohm at b=0, /m) and the model's tc1; rscale carries the")
    L.append("* rsh corner (res_bcs 6.02, res_typ 7.0, res_wcs 7.98 ohm/sq).")
    L.append(".param rscale=%.6g" % rscale)
    L.append(".subckt rsil 1 2 bn")
    L.append(".param w=0.5e-6 l=0.5e-6 b=0 m=1")
    L.append("R1 1 2 r='(9.0e-6/w + 7.0*rscale*l/w)/m' tc1=3.1m")
    L.append(".ends rsil")
    for c in ("bias", "predriver", "driver_ffe"):
        L.append(inline(c))
    L.append("Vdd vdd 0 dc 1.2")
    L.append("Vd d 0 %s" % pwl(BITS))
    L.append("Vdd1 dd 0 %s" % pwl(BITS, delay=UI))  # one-UI-delayed stream
    # mux-output stand-ins: vdd-referenced CML levels, 300 mV single-ended
    for n, src, inv in (("mp", "d", 0), ("mn", "d", 1), ("qp", "dd", 0), ("qn", "dd", 1)):
        e = "v(vdd)-0.3*(1-v(%s))" % src if not inv else "v(vdd)-0.3*v(%s)" % src
        L.append("B%s %s 0 V='%s'" % (n, n, e))
    L.append("Xbias vdd 0 vbn bias")
    L.append("Xprem vdd 0 mp mn vbn pp pn predriver")
    L.append("Xprep vdd 0 qp qn vbn rp rn predriver")
    # post-cursor slice tail biases: FFE off = 0 V, FFE max = vbn on all three
    for i in range(3):
        L.append("Bvbp%d vbp%d 0 V='ffe*v(vbn)'" % (i, i))
    L.append("Xdrv vdd 0 pp pn rp rn vbn vbp0 vbp1 vbp2 cop con driver_ffe")
    for leg, core in (("p", "cop"), ("n", "con")):
        L.append("Rpad%s %s pad%s 4" % (leg, core, leg))
        L.append("Cpad%s pad%s 0 100f" % (leg, leg))
    L.append("Rload padp padn 100")
    L.append("Bvd vd 0 V='v(padp)-v(padn)'")
    L.append(".param ffe=%d" % ffe)
    L.append(".ic v(vbn)=0.9")
    return "\n".join(L) + "\n"


def request(tag, ffe, rname):
    pdk = "libs.tech/ngspice/models/"
    def sections(tag):
        return [{"lib": pdk + "cornerHBT.lib", "section": "hbt_" + tag},
                {"lib": pdk + "cornerCAP.lib", "section": "cap_" + tag}]
    return {
        "engine": "ngspice",
        "netlist": "tx_sizing_%s.sp" % tag,
        "models": {"pdk": "ihp-sg13g2", "lib": pdk + "cornerHBT.lib"},
        "corners": {
            "process": [{"name": rname, "sections": sections(rname)}],
            "supply_v": {"vdd": [1.08, 1.2, 1.32]},
            "temperature_c": [-40, 27, 125],
        },
        "analysis": {"kind": "tran", "args": "2p %.4g" % T_END},
        "measurements": meas_json(ffe),
        "options": {"stage_model_inputs": True, "timeout_s": 1800, "keep_artifacts": False},
    }


RSCALE = {"bcs": 6.02 / 7.0, "typ": 1.0, "wcs": 7.98 / 7.0}
TAGS = [("ffe%d_%s" % (f, t), f, t) for f in (0, 1) for t in ("typ", "bcs", "wcs")]

if __name__ == "__main__":
    # HBT, capacitor and resistor corners move together; the resistor sheet scale and
    # the FFE setting are baked into each deck (the batch worker does not honour
    # corners.params, see sim/tx/README.md).
    for tag, f, t in TAGS:
        with open(os.path.join(HERE, "tx_sizing_%s.sp" % tag), "w") as fh:
            fh.write(deck(f, RSCALE[t]))
        with open(os.path.join(HERE, "tx_sizing_%s.request.json" % tag), "w") as fh:
            json.dump(request(tag, f, t), fh, indent=2)
            fh.write("\n")
