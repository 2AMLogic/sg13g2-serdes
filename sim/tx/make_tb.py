def mos_mm(name, spice, unit="V", limit=None):
    d = dict(name=name, unit=unit, spice=spice)
    if limit is not None:
        d["limits"] = {"max": limit}
    return d


def mux_deck(swing=0.4):
    """swing: per-side clock swing in V, centred on 0.6 V (0.4 V gives the 0.4/0.8 V source)."""
    lo, hi = 0.6 - swing / 2, 0.6 + swing / 2
    L = ["* TX mux2to1_cml sizing bench (issue #80). SIZING EVIDENCE, not a spec result.",
         "* Cells inlined from design/tx/netlists/ with the PDK's own MOS / rsil / rppd / cap_cmim.",
         "* Clock: ideal complementary 5 GHz source, 0.4 V swing (AC-coupled into the squarers; an",
         "* assumption, not a spec value). Data: A held 1, B held 0 (vdd-referenced CML, 300 mV), so",
         "* the output alternates every half clock = a 1010 stream at 10 Gb/s.",
         "* Load: predriver main input (as in the HBT bench) + 20 fF per predriver output.",
         "* Circuit body only: klt sim supplies .lib / .control / .end.",
         "Vdd vdd 0 dc 1.2"]
    for c in ("bias", "predriver", "mux2to1_cml"):
        L.append(inline(c))
    L += ["Vckp ckp 0 pulse(%.4g %.4g 0 20p 20p 80p %.4g)" % (lo, hi, CK_T),
          "Vckn ckn 0 pulse(%.4g %.4g 0 20p 20p 80p %.4g)" % (hi, lo, CK_T),
          "Bdap dap 0 V='v(vdd)'", "Bdan dan 0 V='v(vdd)-0.3'",
          "Bdbp dbp 0 V='v(vdd)-0.3'", "Bdbn dbn 0 V='v(vdd)'",
          "Xbias vdd 0 vbn bias",
          "Xmux vdd 0 ckp ckn dap dan dbp dbn mp mn mux2to1_cml",
          "Xprem vdd 0 mp mn vbn pp pn predriver",
          "Cpp pp 0 20f", "Cpn pn 0 20f",
          "Bvd vd 0 V='v(mp)-v(mn)'",
          ".ic v(vbn)=0.9 v(xmux.nca)=0.55 v(xmux.mida)=0.55 v(xmux.ncb)=0.55 v(xmux.midb)=0.55"]
    return "\n".join(L) + "\n"


def mux_meas():
    w = "from=%.4g to=%.4g" % (MOS_T_SETTLE, MOS_T_END)
    m = [mos_mm("out_diff_max", ".meas tran out_diff_max max v(vd) " + w),
         mos_mm("out_diff_min", ".meas tran out_diff_min min v(vd) " + w),
         mos_mm("out_cm_avg", ".meas tran out_cm_avg avg par('0.5*(v(mp)+v(mn))') " + w),
         mos_mm("rise_pm30mv_s", ".meas tran rise_pm30mv_s trig v(vd) val=-0.03 rise=1 td=%.4g "
                "targ v(vd) val=0.03 rise=1 td=%.4g" % (MOS_T_SETTLE, MOS_T_SETTLE), "s"),
         mos_mm("fall_pm30mv_s", ".meas tran fall_pm30mv_s trig v(vd) val=0.03 fall=1 td=%.4g "
                "targ v(vd) val=-0.03 fall=1 td=%.4g" % (MOS_T_SETTLE, MOS_T_SETTLE), "s"),
         mos_mm("idd_avg", ".meas tran idd_avg avg par('-i(vdd)') " + w, "A")]
    # R3 node stress on the mux HBTs (collector <= 1.32 V, reverse Vbe <= 1.0 V)
    for n, node in (("outp", "mp"), ("outn", "mn")):
        m.append(mos_mm("vc_max_mux_" + n, ".meas tran vc_max_mux_%s max v(%s) %s" % (n, node, w), "V", 1.32))
    for q, (e, b) in {"a1": ("xmux.ea", "dap"), "a2": ("xmux.ea", "dan"),
                      "b1": ("xmux.eb", "dbp"), "b2": ("xmux.eb", "dbn")}.items():
        m.append(mos_mm("vbe_rev_max_mux_" + q,
                        ".meas tran vbe_rev_max_mux_%s max par('v(%s)-v(%s)') %s" % (q, e, b, w), "V", 1.0))
    for q, (c, e) in {"a1": ("mn", "xmux.ea"), "a2": ("mp", "xmux.ea"),
                      "b1": ("mn", "xmux.eb"), "b2": ("mp", "xmux.eb")}.items():
        m.append(mos_mm("vce_max_mux_" + q,
                        ".meas tran vce_max_mux_%s max par('v(%s)-v(%s)') %s" % (q, c, e, w)))
    # clock squarer outputs: MOS gate levels at the tail switches
    m += [mos_mm("sq_a_max", ".meas tran sq_a_max max v(xmux.sqa) " + w),
          mos_mm("sq_a_min", ".meas tran sq_a_min min v(xmux.sqa) " + w)]
    return m


