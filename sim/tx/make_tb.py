"""Generate the TX HBT sizing testbench deck and its klt sim request.

Outputs (committed, regenerated by this script):
  sim/tx/tx_sizing_<ffeN>_<corner>.sp / .request.json   six requests: FFE off / all
  three post slices on, x process typ/bcs/wcs; each is 3 supplies x 3 temperatures

What is simulated: bias, predriver (x2), driver_ffe -- the HBT-and-resistor cells,
inlined from design/tx/netlists/ so the deck is self-contained. pad_esd is not in
the deck: the PDK ESD diode models are not loaded; a lumped 4 ohm + 100 fF
stand-in per leg (the R18 budget, not the cell) loads each output.

The MOS cells (mux2to1_cml, tx_lvl_cml2cmos, ffe_en) are separate benches, one request
per cell, with PSP103 and the real r3_cmc resistors via osdi_preload (issue #80; the
blocker #3 was cleared by PR #76):
  sim/tx/tx_mos_<cell>.sp / .request.json   three requests, each 5 process pairings
                                            (MOS tt/ff/ss/fs/sf) x 3 supplies x 3 temps

Usage: python3 -I sim/tx/make_tb.py     (from the repo root)
"""
