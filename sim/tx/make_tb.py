R7A = {0: "0.06", 1: "0.04"}  # fixed levels below the smallest steady half-swing; see record

def meas_json(ffe):
    out = []
    for name, expr, unit, kind, limit, how, info in MEAS:
        if how == "pp":
            for suffix, fn in (("max", "max"), ("min", "min")):
                out.append(dict(name=name.replace("peak", "peak_" + suffix), unit=unit,
                                spice=".meas tran %s %s %s" % (name.replace("peak", "peak_" + suffix), fn, expr)))
            continue
        d = dict(name=name, unit=unit,
                 spice=".meas tran %s %s %s" % (name, how, "par('%s')" % expr))
        if limit is not None:
            d["limits"] = {"max": limit}
        out.append(d)
    for name, spice, unit in MEAS_RAW:
        out.append(dict(name=name, unit=unit, spice=spice.replace("R7A", R7A[ffe])))
    return out


def deck(ffe, rscale):
    L = []
    L.append("* TX HBT sizing testbench (issue #21). SIZING EVIDENCE, not a spec result.")
    L.append("* Generated by sim/tx/make_tb.py; cells inlined from design/tx/netlists/.")
    L.append("* Not simulated here (MOS, blocked on #3): mux2to1_cml, ffe_en, lvl_cml2cmos.")
    L.append("* Pad/ESD is a lumped stand-in (4 ohm + 100 fF per leg), not the pad_esd cell.")
    L.append("* Circuit body only: klt sim supplies .lib / .control / .end.")
    L.append("* PDK rsil is an OSDI (r3_cmc) model, which the host ngspice cannot load (#3), so")
    L.append("* rsil is a behavioural stand-in using the PDK symbol's own value formula")
    L.append("* (R = 9e-6/w + 7.0*l/w ohm at b=0, /m) and the model's tc1; rscale carries the")
    L.append("* rsh corner (res_bcs 6.02, res_typ 7.0, res_wcs 7.98 ohm/sq).")
    L.append(".param rscale=%.6g" % rscale)
    L.append(".subckt rsil 1 2 bn")
    L.append(".param w=0.5e-6 l=0.5e-6 b=0 m=1")
    L.append("R1 1 2 r='(9.0e-6/w + 7.0*rscale*l/w)/m' tc1=3.1m")
    L.append(".ends rsil")
    for c in ("bias", "predriver", "driver_ffe"):
        L.append(inline(c))
    L.append("Vdd vdd 0 dc 1.2")
    L.append("Vd d 0 %s" % pwl(BITS))
    L.append("Vdd1 dd 0 %s" % pwl(BITS, delay=UI))  # one-UI-delayed stream
    # mux-output stand-ins: vdd-referenced CML levels, 300 mV single-ended
    for n, src, inv in (("mp", "d", 0), ("mn", "d", 1), ("qp", "dd", 0), ("qn", "dd", 1)):
        e = "v(vdd)-0.3*(1-v(%s))" % src if not inv else "v(vdd)-0.3*v(%s)" % src
        L.append("B%s %s 0 V='%s'" % (n, n, e))
    L.append("Xbias vdd 0 vbn bias")
    L.append("Xprem vdd 0 mp mn vbn pp pn predriver")
    L.append("Xprep vdd 0 qp qn vbn rp rn predriver")
    # post-cursor slice tail biases: FFE off = 0 V, FFE max = vbn on all three
    for i in range(3):
        L.append("Bvbp%d vbp%d 0 V='ffe*v(vbn)'" % (i, i))
    L.append("Xdrv vdd 0 pp pn rp rn vbn vbp0 vbp1 vbp2 cop con driver_ffe")
    for leg, core in (("p", "cop"), ("n", "con")):
        L.append("Rpad%s %s pad%s 4" % (leg, core, leg))
        L.append("Cpad%s pad%s 0 100f" % (leg, leg))
    L.append("Rload padp padn 100")
    L.append("Bvd vd 0 V='v(padp)-v(padn)'")
    L.append(".param ffe=%d" % ffe)
    L.append(".ic v(vbn)=0.9")
    return "\n".join(L) + "\n"


def request(tag, ffe, rname):
    pdk = "libs.tech/ngspice/models/"
    def sections(tag):
        return [{"lib": pdk + "cornerHBT.lib", "section": "hbt_" + tag},
                {"lib": pdk + "cornerCAP.lib", "section": "cap_" + tag}]
    return {
        "engine": "ngspice",
        "netlist": "tx_sizing_%s.sp" % tag,
        "models": {"pdk": "ihp-sg13g2", "lib": pdk + "cornerHBT.lib"},
        "corners": {
            "process": [{"name": rname, "sections": sections(rname)}],
            "supply_v": {"vdd": [1.08, 1.2, 1.32]},
            "temperature_c": [-40, 27, 125],
        },
        "analysis": {"kind": "tran", "args": "2p %.4g" % T_END},
        "measurements": meas_json(ffe),
        "options": {"stage_model_inputs": True, "timeout_s": 1800, "keep_artifacts": False},
    }


