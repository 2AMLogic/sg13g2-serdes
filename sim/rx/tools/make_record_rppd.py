"""Render record.md for a sim/rx/records/<id>-rppd-corners/ directory (issue #240).

Reads only that directory, the request files, sim/pdk.json and
layout/toolchain.json. Every number is sizing evidence from a simulation,
never a measurement. The tolerance figures cite
spec/sources/rppd-tolerance-window.md; this renderer never restates them from
memory -- the window rsh values are read out of the request's corners.params
and the geometry out of the bench deck, so the record cannot disagree with
the run that produced it.
"""
import json
import pathlib
import re
import sys

out = pathlib.Path(sys.argv[1])
rx = out.parent.parent
repo = rx.parent.parent
sys.path.insert(0, str(repo / "sim" / "tools"))
import record_common as rc  # noqa: E402
pdk, tool = rc.load_pins(repo)
codes = rc.exit_codes(out)

MAIN, WIN = "pad_ac_rppd", "pad_ac_rppd_p11win"
main_r, main_err = rc.report_or_error(out, MAIN)
win_r, win_err = rc.report_or_error(out, WIN)
reports = {MAIN: main_r, WIN: win_r}

val = rc.val


def z(c, n):
    i = val(c, n)
    return None if not i else 1.0 / i


def f(x, spec="{:.2f}", none="n/a"):
    return none if x is None else spec.format(x)


# The window rsh values, read out of the request that ran them.
win_req = json.loads((rx / f"{WIN}.request.json").read_text())
RSH_LO, RSH_HI = win_req["corners"]["params"]["rsh_rppd"]
RSH_TYP = 260.0  # cornerRES.lib res_typ, quoted in the source note

# The rppd geometry, read out of the bench deck that ran.
deck = (rx / f"{MAIN}.sp").read_text()
geo = re.search(r"XRtp \S+ \S+ 0 rppd w=(\S+) l=(\S+) m=(\d+)", deck)
if not geo:
    raise SystemExit(f"make_record_rppd.py: no rppd termination instance found in {MAIN}.sp")
W_U, L_U, M = geo.groups()
W_UM = float(W_U.rstrip("u"))
# The r3_cmc terminal resistance (model rc = rz = rzspec/w, RCRPPD 35 ohm·um
# on p.11): in series with the channel term and NOT divided by m. The bench
# records of this family reproduce R_side = rz + rsh*k within ~0.7 %.
RZ = 35.0 / W_UM
K = float(L_U.rstrip("u")) / (int(M) * (W_UM + 0.006))   # ohm per (ohm/sq)
R_SIDE_TYP = RZ + RSH_TYP * K

L = [f"# RX termination rppd corner record {out.name}", "",
     "**Sizing evidence, not a spec result and not a measurement.** Every figure below is",
     "read from the klt sim reports in this directory. R9's resistor-corner column now has a",
     "committed source: [`spec/sources/rppd-tolerance-window.md`](../../../spec/sources/rppd-tolerance-window.md),",
     "which quotes the PDK process spec Rev. 1.2 p.11 table and derives the window edges used",
     "by the two window members below. R9's own numbers are unchanged by this record.", "",
     "## The three tolerance sources (as reported in the source note; not reconciled)", "",
     "| source | rsh_rppd (ohm/sq) | vs 260 |",
     "|---|---|---|",
     "| PDK process spec Rev. 1.2 p.11 s.2.8 (RSRPPD min/target/max) | 235 / 260 / 285 | -9.62 % / +9.62 % |",
     "| cornerRES.lib sections res_bcs/res_typ/res_wcs | 234.0 / 260.0 / 286.0 | -10.00 % / +10.08 % |",
     "| DR-014 (PR #47 head `8f213e3`, not on main) | -- | about -10.5 % / +11.8 %, **not reproducible from p.11** |", "",
     "The library corners envelope the p.11 sheet window; neither matches DR-014's figure.",
     "The mismatch is reported here and in the source note, not edited into any spec row.", "",
     "## Pins",
     f"- PDK: {pdk['source']} {pdk['release_tag']}, tarball sha256 `{pdk['tarball_sha256']}` (sim/pdk.json)",
     f"- klt: `{tool['klt_last_verified_commit']}` (layout/toolchain.json)",
     "- Schematics/netlists: design/rx/ at the commit named in the record id (inlined by the",
     "  generated bench; netlist staleness gate `design/check-netlists.sh`); the bench bodies",
     "  and requests are generated by sim/rx/tools/gen_requests.py",
     "", "## Runs"]
for name in (MAIN, WIN):
    line = [l for l in codes if l.startswith(name)]
    r = reports[name]
    L += ["", f"### {name}",
          f"- command: `cd sim/rx && klt sim --format json --wait-for-capacity 900 --report-out records/{out.name}/{name}.report.json {name}.request.json`",
          f"- {line[0] if line else 'no exit code recorded'}"]
    if r is None:
        L.append("- NO REPORT: " + (main_err if name == MAIN else win_err)[:300])
        continue
    env = r["environment"]
    rem = env.get("remote") or {}
    L.append(f"- status: **{r['status']}** ({r['passed']}/{r['corner_count']} corners pass, {r['errored']} error); engine host {env.get('engine_host')}, ngspice {env.get('engine_version')}, backend job `{rem.get('job_id')}`")

L += ["", "## Bench",
      "",
      f"The two ideal 50 ohm legs of `design/rx/netlists/rx_term_pad.spice` are replaced by PDK",
      f"`rppd` instances (r3_cmc OSDI via `osdi_preload`, as on the TX MOS benches): w={W_U},",
      f"l={L_U}, m={M} parallel strips. The model's resistance is R_side = rz + rsh*l/(m*(w+xw)),",
      f"with the terminal resistance rz = 35 ohm·um / w = {RZ:.1f} ohm (RCRPPD p.11, model",
      f"`rzspec`), in series with the channel and **not** divided by m -- sizing for the",
      f"channel term 50 - {RZ:.1f} = {50 - RZ:.1f} ohm gives {R_SIDE_TYP:.3f} ohm per side,",
      f"{2 * R_SIDE_TYP:.3f} ohm differential at rsh = 260. The terminal term also compresses",
      f"the corner span: a +-10 % rsh move is about {100 * RSH_TYP * K / R_SIDE_TYP:.1f} % of the finished",
      "resistor. w = 2 um is the p.11 precision recommendation; the layout minimums (0.50 um",
      "width and SalBlock length) are met. Everything else is the pad_ac bench as-is:",
      "PLACEHOLDER 50 fF pad capacitance, ideal 4 ohm metal series stand-ins, ideal",
      "CTLE-internal resistors, code-0 CTLE hanging on the pad. |Zdiff| = 1/|I_diff| for a",
      "1 V differential AC drive; the 0.1 GHz point stands in for the DC resistance.", "",
      "### Grid over the RES library corners (27 points)", "",
      "RES corner as the named process axis, ganged with the same-index HBT/CAP/DIO sections",
      "(hbt_typ/bcs/wcs + cap_typ/bcs/wcs + dio_tt/ff/ss) x 1.08/1.2/1.32 V x -40/27/125 C.",
      "First-look comparison with R9's draft target: 100 ohm differential +-10 %, i.e.",
      "|Zdiff| in 90-110 ohm at the 0.1 GHz point.", "",
      "| corner | \\|Zdiff\\| 0.1 GHz (ohm) | \\|Zdiff\\| 5 GHz (ohm) | R9 draft window (0.1 GHz) |",
      "|---|---|---|---|"]
if main_r:
    zd = []
    for c in main_r["corners"]:
        z0, z5 = z(c, "pad_idiff_0p1g_a"), z(c, "pad_idiff_5g_a")
        if z0 is not None:
            zd.append((z0, c["corner_id"]))
        ok = z0 is not None and 90.0 <= z0 <= 110.0
        L.append(f"| {c['corner_id']} | {f(z0, '{:.1f}')} | {f(z5, '{:.1f}')} | {'in' if ok else 'OUT'} |")
    if zd:
        lo, hi = min(zd), max(zd)
        z5s = [z(c, "pad_idiff_5g_a") for c in main_r["corners"]]
        z5s = [v for v in z5s if v is not None]
        L += ["",
              f"- Corners inside the R9 draft window at 0.1 GHz: {len([1 for v, _ in zd if 90.0 <= v <= 110.0])} of {len(zd)}.",
              f"- Span at 0.1 GHz: {lo[0]:.1f} ohm ({lo[0] - 100.0:+.1f} %) at {lo[1]} to {hi[0]:.1f} ohm ({hi[0] - 100.0:+.1f} %) at {hi[1]}.",
              f"- Span at 5 GHz: {f(min(z5s), '{:.1f}')} to {f(max(z5s), '{:.1f}')} ohm." if z5s else "- Span at 5 GHz: no data."]
L += ["", "### p.11 window members (2 points)", "",
      f"Same circuit, typical ganged sections, nominal supply and 27 C, with `rsh_rppd`",
      f"overridden to the source-note window edges ({RSH_LO:.3f} and {RSH_HI:.3f} ohm/sq: the",
      "p.11 min/max rsh and line-width-delta columns folded into one effective sheet",
      "resistance at w = 2 um -- the r3_cmc model has no width-delta parameter). These are",
      "derived figures, labelled arith in the source note; they are not PDK library corners.", "",
      "| corner | rsh_rppd (ohm/sq) | \\|Zdiff\\| 0.1 GHz (ohm) | \\|Zdiff\\| 5 GHz (ohm) |",
      "|---|---|---|---|"]
if win_r:
    typ = None
    if main_r:
        for c in main_r["corners"]:
            if c["corner_id"] == "res_typ/1.200V/27C":
                typ = z(c, "pad_idiff_0p1g_a")
    for c in win_r["corners"]:
        rsh = float(str(c["corner_id"]).split("rsh_rppd=")[1])
        z0, z5 = z(c, "pad_idiff_0p1g_a"), z(c, "pad_idiff_5g_a")
        L.append(f"| {c['corner_id']} | {rsh:g} | {f(z0, '{:.1f}')} | {f(z5, '{:.1f}')} |")
    # Consistency guard: the override must have moved |Zdiff| by roughly the
    # model-resistance ratio (rz terminal term included). If it did not, the
    # numbers are typ-like, not window edges -- say so loudly instead of
    # recording them as the window.
    if typ:
        L.append("")
        for c in win_r["corners"]:
            rsh = float(str(c["corner_id"]).split("rsh_rppd=")[1])
            z0 = z(c, "pad_idiff_0p1g_a")
            if z0 is None:
                continue
            got = z0 / typ
            want = (RZ + rsh * K) / (RZ + RSH_TYP * K)
            verdict = "ok" if abs(got / want - 1.0) <= 0.02 else ("**WARNING: override may not have applied**" if abs(got - 1.0) <= 0.02 else "unexpected (see the ratio)")
            L.append(f"- rsh={rsh:g}: |Zdiff| ratio vs res_typ/1.200V/27C measured {got:.4f}, expected {want:.4f} (rz included) -- {verdict}.")
L += ["", "## Not simulated",
      "",
      "- SDD11 / return loss to 5 GHz (R9's AC half, gate G4): not simulated; the pad",
      "  capacitance is still the 50 fF placeholder, and grading needs the extracted pad (#24/#28).",
      "- Everything else in design/rx still uses ideal resistors: the CTLE-internal resistors,",
      "  the latch and clock-buffer loads, and the 4 ohm metal series stand-ins in this very",
      "  bench (metal resistance, not rppd -- replacing them with poly would be the wrong physics).",
      "- rppd mismatch / Monte Carlo (`res_typ_stat`, MATRPPD 15 nm), temperature-coefficient",
      "  extremes beyond the -40/27/125 C axis, and any trim mechanism (#143 owns the",
      "  termination re-point): not simulated.",
      "- A measured (silicon) termination resistance: does not exist; nothing here is measured."]
(out / "record.md").write_text("\n".join(L) + "\n")
print(f"make_record_rppd.py: wrote {out / 'record.md'}")
